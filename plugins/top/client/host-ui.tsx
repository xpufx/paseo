import React from "react";
import {
  HostModalSection as BaseHostModalSection,
  ModalBodyScrollOwnerContext,
  type HostModalSectionProps,
} from "@xpufx/paseo-plugin-ui";

/**
 * Top pill modal sections operate under the host single-scroller model
 * (`hostScroll: true`, xpufx-org/paseo#975, #1054, #1258).
 * Ensures fluid, unconstrained height when rendered with or without an outer
 * host provider in testing harnesses.
 */
export function HostModalSection({ children, style, ...props }: HostModalSectionProps) {
  return (
    <ModalBodyScrollOwnerContext.Provider value="host">
      <BaseHostModalSection style={style} {...props}>
        {children}
      </BaseHostModalSection>
    </ModalBodyScrollOwnerContext.Provider>
  );
}

